"""gen.sh's last step: prefixes the internal symbols of llc's PTX with `__sjm_`.

PTX modules have one namespace, so musl's internal names (`exp`, `fact`, ...) could collide with
the kernel's; sjb2ptx rejects kernel names that start with `__sj`. Instructions such as
`sqrt.rn.f64` are followed by a dot and are left alone.
"""

import re
import sys

src, dst = sys.argv[1], sys.argv[2]
text = open(src).read()

if re.search(r"^\.extern", text, re.M):
    sys.exit("post.py: the library calls functions it does not define:\n"
             + "\n".join(re.findall(r"^\.extern.*$", text, re.M)))

names = set(re.findall(r"^\.func\s+(?:\([^)]*\)\s*)?([A-Za-z_$][\w$]*)", text, re.M))
names |= set(re.findall(r"^\.global\s[^=;\[]*?([A-Za-z_$][\w$]*)\s*\[", text, re.M))
names -= {n for n in names if n.startswith("__sj_")}

pattern = re.compile(r"(?<![\w.%$])(" + "|".join(sorted(map(re.escape, names))) + r")(?![\w.$])")
text = pattern.sub(lambda m: "__sjm_" + m.group(1), text)
text = text.replace("// Generated by LLVM NVPTX Back-End",
                    "// Generated by LLVM NVPTX Back-End through src/ptx/libm/gen.sh: do not edit")
open(dst, "w").write(text)
