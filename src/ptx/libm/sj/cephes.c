/* coef[0..=n] */
static double polevl(double x, const double *coef, int n)
{
    double ans = coef[0];
    for (int i = 1; i <= n; i++)
        ans = ans * x + coef[i];
    return ans;
}

/* the leading coefficient 1 implied, coef[0..n] */
static double p1evl(double x, const double *coef, int n)
{
    double ans = x + coef[0];
    for (int i = 1; i < n; i++)
        ans = ans * x + coef[i];
    return ans;
}

static double chbevl(double x, const double *array, int n)
{
    double b0 = array[0];
    double b1 = 0.0;
    double b2 = 0.0;
    for (int i = 1; i < n; i++) {
        b2 = b1;
        b1 = b0;
        b0 = x * b1 - b2 + array[i];
    }
    return 0.5 * (b0 - b2);
}

void cephes_sici(double x, double *si, double *ci)
{
    int sign = 0;
    double s, c;
    if (x < 0.0) {
        x = -x;
        sign = 1;
    }
    if (x == 0.0) {
        *si = 0.0;
        *ci = -INFINITY;
        return;
    }
    if (x > 1.0e9) {
        if (isinf(x)) {
            if (sign) {
                *si = -M_PI_2_;
                *ci = NAN;
            } else {
                *si = M_PI_2_;
                *ci = 0.0;
            }
            return;
        }
        s = M_PI_2_ - cos(x) / x;
        c = sin(x) / x;
    } else if (x > 4.0) {
        double sx = sin(x);
        double cx = cos(x);
        double z = 1.0 / (x * x);
        double f, g;
        if (x < 8.0) {
            f = polevl(z, FN4, 6) / (x * p1evl(z, FD4, 7));
            g = z * polevl(z, GN4, 7) / p1evl(z, GD4, 7);
        } else {
            f = polevl(z, FN8, 8) / (x * p1evl(z, FD8, 8));
            g = z * polevl(z, GN8, 8) / p1evl(z, GD8, 9);
        }
        s = M_PI_2_ - f * cx - g * sx;
        c = f * sx - g * cx;
    } else {
        double z = x * x;
        s = x * polevl(z, SN, 5) / polevl(z, SD, 5);
        c = z * polevl(z, CN, 5) / polevl(z, CD, 5);
        c = EULER + log(x) + c; /* real part if x < 0 */
    }
    *si = sign ? -s : s;
    *ci = c;
}

/* 3F0(a1, a2, a3; z), an asymptotic series: z must be large enough */
static double hyp3f0(double a1, double a2, double a3, double z)
{
    double m = pow(z, -1.0 / 3.0);
    long maxiter = (long)m < 50 ? (long)m : 50;
    double term = 1.0;
    double sum = term;
    for (long n = 0; n < maxiter; n++) {
        term *= (a1 + (double)n) * (a2 + (double)n) * (a3 + (double)n) * z / (double)(n + 1);
        sum += term;
        if (fabs(term) < 1e-13 * fabs(sum) || term == 0.0)
            break;
    }
    double err = fabs(term);
    if (err > 1e-13 * fabs(sum))
        return NAN;
    return sum;
}

void cephes_shichi(double x, double *shi, double *chi)
{
    int sign = 0;
    double s, c;
    if (x < 0.0) {
        x = -x;
        sign = 1;
    }
    if (x == 0.0) {
        *shi = 0.0;
        *chi = -INFINITY;
        return;
    }
    if (x >= 8.0) {
        if (x < 18.0) {
            double a = (576.0 / x - 52.0) / 10.0;
            double k = exp(x) / x;
            s = k * chbevl(a, S1, 22);
            c = k * chbevl(a, C1, 23);
        } else if (x <= 88.0) {
            double a = (6336.0 / x - 212.0) / 70.0;
            double k = exp(x) / x;
            s = k * chbevl(a, S2, 23);
            c = k * chbevl(a, C2, 24);
        } else if (x > 1000.0) {
            *shi = sign ? -INFINITY : INFINITY;
            *chi = INFINITY;
            return;
        } else {
            double a = hyp3f0(0.5, 1.0, 1.0, 4.0 / (x * x));
            double b = hyp3f0(1.0, 1.0, 1.5, 4.0 / (x * x));
            double si = cosh(x) / x * a + sinh(x) / (x * x) * b;
            double ci = sinh(x) / x * a + cosh(x) / (x * x) * b;
            *shi = sign ? -si : si;
            *chi = ci;
            return;
        }
    } else {
        double z = x * x;
        double a = 1.0;
        double k = 2.0;
        s = 1.0;
        c = 0.0;
        for (;;) {
            a *= z / k;
            c += a / k;
            k += 1.0;
            a /= k;
            s += a / k;
            k += 1.0;
            if (!(fabs(a / s) > MACHEP))
                break;
        }
        s *= x;
    }
    if (sign)
        s = -s;
    *shi = s;
    *chi = EULER + log(x) + c;
}
