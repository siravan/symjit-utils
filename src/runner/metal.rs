//! `pacman runner --metal`: the runner of one execution on an Apple GPU (`docs/METAL.md`).
//!
//! The leaves are Metal kernels of `sjb2msl` (`crate::msl`), `pacman_leaf<k>` with the leaf's
//! planes compiled in (`MslOptions::mapping`), all in one source, `kernels/leaves.metal`, which
//! `runner.m` embeds (`.incbin`) and the Metal framework compiles when the library first runs
//! (Metal caches the result). Metal has no f64, so the kernels are f32 or mixed f32/df64
//! (`MetalPrecision`). The arena on the GPU is one shared f32 buffer in blocks of
//! `PACMAN_RUNNER_BLOCK` (default 4096) points, each block all `NUM_PLANES` planes of its points
//! (a kernel's planes are a block apart, not a call: short strides keep a block in the caches);
//! a mixed runner adds the low parts of the planes from `FIRST_F64` on (the momenta, the zero
//! plane, the parameters), which the df64 inputs read, in the same blocks. Memory is unified, so
//! the conversions are done on the CPU: the planes read before they are written are rounded into
//! the f32 arena (and their low parts split off), and the planes copied back are widened. Every
//! leaf runs on a block before the next block, all in one command buffer.

use std::collections::HashMap;
use std::fmt::Write;
use std::path::Path;
use std::process::Command;

use anyhow::{anyhow, bail, Context, Result};

use super::{first_f64_plane, tables_c, Spec, MAIN_C, REDUCE_C, RUNNER_H};
use crate::msl::{prelude, MslCounts, MslOptions};
use crate::SavedModel;

/// The Objective-C part of `runner.m`.
const RUN_METAL_M: &str = include_str!("run_metal.m");

/// The precision of a Metal runner's kernels.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum MetalPrecision {
    /// f32 kernels on an f32 arena
    F32,
    /// mixed f32/df64 kernels (`ptx::mixed`'s `need` rule): the momenta, the zero plane and the
    /// parameters are df64 inputs, divisions and what their divisors depend on df64, the rest
    /// f32
    Mixed,
}

/// The Metal source of `spec`'s leaves (`prelude()`, then `pacman_leaf<k>` per leaf) and the
/// operations it does by type. `settings` as for `objects`.
pub fn metal_source(
    spec: &Spec,
    members: &HashMap<&str, &[u8]>,
    precision: MetalPrecision,
    settings: &[(String, String)],
) -> Result<(String, MslCounts)> {
    let first_f64 = first_f64_plane(spec);
    let mut source = prelude();
    let mut counts = MslCounts::default();
    for (k, call) in spec.calls.iter().enumerate() {
        let bytes = members
            .get(call.member.as_str())
            .ok_or_else(|| anyhow!("evaluators.pacbin has no kernel `{}`", call.member))?;
        let mut model = SavedModel::read_with(&mut &bytes[..], settings)
            .with_context(|| format!("cannot read `{}`", call.member))?;
        if !model.config().direct_arena() {
            bail!("`{}` is not a plane (direct-arena) kernel", call.member);
        }
        let mut options = MslOptions::new(&format!("pacman_leaf{}", k));
        options.mapping = Some(call.inputs.iter().chain(&call.outputs).copied().collect());
        if precision == MetalPrecision::Mixed {
            options.mixed = Some(call.inputs.iter().map(|&p| p >= first_f64).collect());
            options.lo_first = first_f64;
        }
        let msl = model.msl(&options).with_context(|| {
            format!(
                "{}: cannot compile `{}` into Metal",
                call.label, call.member
            )
        })?;
        counts.df64_ops += msl.counts.df64_ops;
        counts.f32_ops += msl.counts.f32_ops;
        source.push('\n');
        source.push_str(&msl.kernel);
    }
    Ok((source, counts))
}

/// `runner.m` of the Metal runner: the execution `spec`, its embedded source
/// (`kernels/leaves.metal`) and `pacman_runner_v1_run` on the GPU.
pub fn runner_metal_m(spec: &Spec, precision: MetalPrecision) -> String {
    let mut s = String::new();
    let _ = writeln!(
        s,
        "/* runner.m: the execution {} of {} ({} leaves, {} arena planes) on an Apple GPU (Metal),\n\
         \x20  generated by pacman {}. The interface is in pacman_runner.h. */\n\n\
         #import <Foundation/Foundation.h>\n\
         #import <Metal/Metal.h>\n\
         #include <pthread.h>\n\
         #include <stddef.h>\n\
         #include <stdint.h>\n\
         #include <stdio.h>\n\
         #include <stdlib.h>\n\
         #include <string.h>\n\
         #include <time.h>\n\n\
         #include \"pacman_runner.h\"\n",
        spec.execution,
        spec.process,
        spec.calls.len(),
        spec.arena.len(),
        env!("CARGO_PKG_VERSION")
    );
    let _ = writeln!(
        s,
        "/* 1: mixed f32/df64 kernels: the planes from FIRST_F64 on (momenta, the zero plane,\n\
         \x20  parameters) are df64 inputs, their low parts in a second buffer */\n\
         #define MIXED {}\n#define FIRST_F64 {}u\n",
        (precision == MetalPrecision::Mixed) as u8,
        first_f64_plane(spec)
    );
    s.push_str(&tables_c(spec));
    s.push_str(
        "/* the leaves' kernels: kernels/leaves.metal, embedded (NUL-terminated) */\n\
         __asm__(\".section __TEXT,__const\\n\"\n\
         \x20       \".globl _pacman_metal_source\\n.private_extern _pacman_metal_source\\n\"\n\
         \x20       \"_pacman_metal_source:\\n.incbin \\\"kernels/leaves.metal\\\"\\n\"\n\
         \x20       \".globl _pacman_metal_source_end\\n.private_extern _pacman_metal_source_end\\n\"\n\
         \x20       \"_pacman_metal_source_end:\\n.byte 0\\n\"\n\
         \x20       \".text\\n\");\n\
         extern const char pacman_metal_source[], pacman_metal_source_end[];\n\n",
    );
    s.push_str(REDUCE_C);
    s.push_str(RUN_METAL_M);
    s
}

const FRAMEWORKS: [&str; 4] = ["-framework", "Metal", "-framework", "Foundation"];

/// The `Makefile` of the Metal runner.
pub fn makefile_metal() -> String {
    format!(
        "# generated by pacman runner --metal\n\
         CC ?= cc\n\
         CFLAGS ?= -O1\n\
         FRAMEWORKS = {}\n\n\
         all: runner librunner.so\n\n\
         runner.o: runner.m pacman_runner.h kernels/leaves.metal\n\
         \t$(CC) $(CFLAGS) -fobjc-arc -ffp-contract=off -fPIC -c runner.m -o runner.o\n\n\
         librunner.so: runner.o\n\
         \t$(CC) -shared -o librunner.so runner.o $(FRAMEWORKS)\n\n\
         runner: main.c runner.o pacman_runner.h\n\
         \t$(CC) $(CFLAGS) -o runner main.c runner.o $(FRAMEWORKS)\n",
        FRAMEWORKS.join(" ")
    )
}

/// Writes the Metal runner of `spec` into `dir`: `kernels/leaves.metal` (`source`, from
/// `metal_source`), `runner.m`, `pacman_runner.h`, `main.c`, `Makefile`.
pub fn write_metal(dir: &Path, spec: &Spec, source: &str, precision: MetalPrecision) -> Result<()> {
    let write = |name: &str, bytes: &[u8]| -> Result<()> {
        let path = dir.join(name);
        if let Some(parent) = path.parent() {
            std::fs::create_dir_all(parent)
                .with_context(|| format!("cannot create `{}`", parent.display()))?;
        }
        std::fs::write(&path, bytes).with_context(|| format!("cannot write `{}`", path.display()))
    };
    write("kernels/leaves.metal", source.as_bytes())?;
    write("runner.m", runner_metal_m(spec, precision).as_bytes())?;
    write("pacman_runner.h", RUNNER_H.as_bytes())?;
    write("main.c", MAIN_C.as_bytes())?;
    write("Makefile", makefile_metal().as_bytes())?;
    Ok(())
}

/// Builds `runner` and `librunner.so` of the Metal runner in `dir` with the C compiler `cc`
/// (clang: Objective-C), as its `Makefile` does.
pub fn build_metal(dir: &Path, cc: &str) -> Result<()> {
    let steps: Vec<Vec<&str>> = vec![
        vec![
            "-O1",
            "-fobjc-arc",
            "-ffp-contract=off",
            "-fPIC",
            "-c",
            "runner.m",
            "-o",
            "runner.o",
        ],
        [
            &["-shared", "-o", "librunner.so", "runner.o"][..],
            &FRAMEWORKS,
        ]
        .concat(),
        [
            &["-O1", "-o", "runner", "main.c", "runner.o"][..],
            &FRAMEWORKS,
        ]
        .concat(),
    ];
    for args in steps {
        let out = Command::new(cc)
            .args(&args)
            .current_dir(dir)
            .output()
            .with_context(|| format!("cannot run `{}`", cc))?;
        if !out.status.success() {
            bail!(
                "`{} {}` failed:\n{}",
                cc,
                args.join(" "),
                String::from_utf8_lossy(&out.stderr)
            );
        }
    }
    Ok(())
}
