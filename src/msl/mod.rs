    // the formulas of the PTX backend (x86's scalar generator)
    fn times_complex(&mut self, xd: Reg, yd: Reg, x1: Reg, y1: Reg, x2: Reg, y2: Reg) -> bool {
        let (xd, yd) = (self.reg(xd), self.reg(yd));
        let (x1, y1, x2, y2) = (self.reg(x1), self.reg(y1), self.reg(x2), self.reg(y2));
        self.emit(format!("x2 = fma({}, {}, -({} * {}));", x1, x2, y1, y2));
        self.emit(format!("x3 = {} * {};", x1, y2));
        self.emit(format!("{} = fma({}, {}, x3);", yd, x2, y1));
        self.mov(xd, "x2".into());
        true
    }

    fn divide_complex(&mut self, xd: Reg, yd: Reg, x1: Reg, y1: Reg, x2: Reg, y2: Reg) -> bool {
        let (xd, yd) = (self.reg(xd), self.reg(yd));
        let (x1, y1, x2, y2) = (self.reg(x1), self.reg(y1), self.reg(x2), self.reg(y2));
        self.emit(format!("x2 = fma({}, {}, {} * {});", x1, x2, y1, y2));
        self.emit(format!("x3 = fma({}, {}, -({} * {}));", x2, y1, x1, y2));
        self.emit(format!("x1 = fma({}, {}, {} * {});", y2, y2, x2, x2));
        self.emit(format!("{} = x2 / x1;", xd));
        self.emit(format!("{} = x3 / x1;", yd));
        true
    }

